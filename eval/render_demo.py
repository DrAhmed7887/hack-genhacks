    ne = backtest["nasa_evaluation"]
    ho = ne["N2_pooled"]["heldout_2024_2025"]
    p2, n2 = ho["P2"], ho["N2"]
    paired = ne["N1_pooled"]["heldout_2024_2025"]["paired_common_rows"]
    n1, c0, r2 = paired["N1"], paired["C0_14d"], paired["R2"]
    mo = next(r for r in ne["per_city_species"] if r["city"] == "madrid" and r["species"] == "olive")
    mo_ho = mo["N2"]["splits"]["heldout_2024_2025"]
    pct = lambda v: f"{v * 100:.1f}%"  # noqa: E731
    pct0 = lambda v: f"{v * 100:.0f}%"  # noqa: E731
    lg = ne["latency_sensitivity_lag3"]["N2_pooled"]["heldout_2024_2025"]["N2"]
