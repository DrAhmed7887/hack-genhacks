"""Render the demo onset table from eval/results/backtest.json.

Pure Python, no browser. The rows are written as static HTML between two
marker comments in demo/index.html, so the page shows them without JS and
the tests can parse them back out of the HTML.

    .venv/bin/python eval/render_demo.py           # rewrite demo/index.html
    .venv/bin/python eval/render_demo.py --check   # exit 1 if the HTML is stale
"""
from __future__ import annotations

import argparse
import csv
import html
import json
import sys
from dataclasses import dataclass
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[1]
BACKTEST_JSON = REPO_ROOT / "eval" / "results" / "backtest.json"
DEMO_HTML = REPO_ROOT / "demo" / "index.html"
PATIENTS_CSV = REPO_ROOT / "data" / "patients.csv"
THRESHOLDS_JSON = REPO_ROOT / "rules" / "thresholds.json"
CACHE_DIR = REPO_ROOT / "data" / "cache"

sys.path.insert(0, str(REPO_ROOT))
from src import reminders  # noqa: E402

CONSOLE_BEGIN = "<!-- NURSE_CONSOLE_DATA:BEGIN (generated by eval/render_demo.py; do not edit) -->"
CONSOLE_END = "<!-- NURSE_CONSOLE_DATA:END -->"
SPECIES = ("olive", "grass", "birch")

# (id, label, cache file, date, kind). A None file means a simulated crossing.
SCENARIOS = (
    ("valencia_control", "Valencia · 2025-05-28 (CAMS Replay — Below Threshold, Control Case)",
     "open_meteo_valencia_demo.csv", "2025-05-28", "replay"),
    ("madrid_grass", "Madrid · 2025-05-18 (CAMS Replay — Grass Alert >= 35 grains/m³)",
     "open_meteo_madrid_facf.csv", "2025-05-18", "replay"),
    ("basel_birch", "Basel · 2025-04-05 (CAMS Replay — Birch Alert >= 30 grains/m³)",
     "open_meteo_basel_pbs.csv", "2025-04-05", "replay"),
    ("olive_sim", "Clinic Threshold-Crossing Replay · Olive Alert >= 162 grains/m³ (Scenario)",
     None, None, "simulated"),
)
SIMULATED_MEANS = {"olive": 165.0, "grass": 0.0, "birch": 0.0}

BEGIN = "<!-- ONSET_ROWS:BEGIN (generated by eval/render_demo.py; do not edit) -->"
END = "<!-- ONSET_ROWS:END -->"

NO_DATE = "no alert"
NO_LEAD = "n/a"

COLUMNS = (
    "City",
    "Species",
    "Year",
    "Observed onset",
    "R2 alert",
    "R2 lead",
    "P2 alert",
    "P2 lead",
    "C0 alert",
    "C0 lead",
    "R2 status",
)


@dataclass(frozen=True)
class OnsetRow:
    city: str
    species: str
    year: str
    observed_onset: str | None
    r2_onset: str | None
    r2_lead: int | None
    p2_onset: str | None
    p2_lead: int | None
    c0_onset: str | None
    c0_lead: int | None
    r2_fired_before_onset: bool
    r2_missed_season: bool


def onset_rows(backtest: dict) -> list[OnsetRow]:
    """Every city-species-year row from results[].onset_by_year, in file order."""
    rows: list[OnsetRow] = []
    for result in backtest["results"]:
        for year in sorted(result["onset_by_year"]):
            o = result["onset_by_year"][year]
            rows.append(
                OnsetRow(
                    city=result["city"],
                    species=result["species"],
                    year=year,
                    observed_onset=o["observed_onset"],
                    r2_onset=o["R2_onset"],
                    r2_lead=o["R2_lead_days"],
                    p2_onset=o["P2_onset"],
                    p2_lead=o["P2_lead_days"],
                    c0_onset=o["C0_onset"],
                    c0_lead=o["C0_lead_days"],
                    r2_fired_before_onset=o["R2_fired_before_onset"],
                    r2_missed_season=o["R2_missed_season"],
                )
            )
    return rows


def fmt_date(value: str | None) -> str:
    return NO_DATE if value is None else value


def fmt_lead(value: int | None) -> str:
    if value is None:
        return NO_LEAD
    return f"+{value}" if value > 0 else str(value)


def r2_status(row: OnsetRow) -> str:
    if row.r2_missed_season:
        return "missed season"
    if row.r2_fired_before_onset:
        return "on time or early"
    return "late"


def row_cells(row: OnsetRow) -> tuple[str, ...]:
    """The exact text of each cell, in COLUMNS order."""
    return (
        row.city.capitalize(),
        row.species,
        row.year,
        fmt_date(row.observed_onset),
        fmt_date(row.r2_onset),
        fmt_lead(row.r2_lead),
        fmt_date(row.p2_onset),
        fmt_lead(row.p2_lead),
        fmt_date(row.c0_onset),
        fmt_lead(row.c0_lead),
        r2_status(row),
    )


def render_tbody(rows: list[OnsetRow], indent: str = "          ") -> str:
    lines = [indent + BEGIN]
    for row in rows:
        cells = "".join(f"<td>{html.escape(c)}</td>" for c in row_cells(row))
        cls = "missed" if row.r2_missed_season else ("late" if not row.r2_fired_before_onset else "early")
        lines.append(f'{indent}<tr class="onset-{cls}">{cells}</tr>')
    lines.append(indent + END)
    return "\n".join(lines)


def inject(page: str, tbody: str) -> str:
    start = page.index(BEGIN)
    stop = page.index(END, start) + len(END)
    line_start = page.rfind("\n", 0, start) + 1
    return page[:line_start] + tbody + page[stop:]


def daily_means(csv_name: str, date: str) -> dict[str, float]:
    """Raw, unrounded mean of the 24 hourly CAMS values for one UTC date.

    Thresholds are compared against these raw values; round only for display.
    """
    with (CACHE_DIR / csv_name).open() as fh:
        rows = [r for r in csv.DictReader(fh) if r["time_utc"].startswith(date)]
    assert len(rows) == 24, f"{csv_name} {date}: {len(rows)} hourly rows"
    return {sp: sum(float(r[f"{sp}_pollen"]) for r in rows) / len(rows) for sp in SPECIES}


def alerting_species(means: dict[str, float], alert: dict[str, float]) -> str | None:
    """The one species whose raw (unrounded) mean is at or above its alert level.

    Raises ValueError if more than one species crosses at once, so a crossing is
    never silently discarded.
    """
    hits = [sp for sp in SPECIES if float(means[sp]) >= alert[sp]]
    if len(hits) > 1:
        raise ValueError(f"Multiple species crossed thresholds simultaneously: {hits}")
    return hits[0] if hits else None


def console_data() -> dict:
    """Everything the nurse console shows, computed by src.reminders."""
    thresholds = json.loads(THRESHOLDS_JSON.read_text())
    with PATIENTS_CSV.open() as fh:
        patients = [reminders.patient_from_row(r) for r in csv.DictReader(fh)]
    scenarios = []
    for sid, label, csv_name, date, kind in SCENARIOS:
        means = SIMULATED_MEANS if csv_name is None else daily_means(csv_name, date)
        species = alerting_species(means, thresholds["alert"])
        batch = reminders.build_batch(patients, species) if species else []
        by_id = {p.patient_id: p for p in patients}
        drafts = []
        for m in batch:
            p = by_id[m.patient_id]
            drafts.append({
                "patient_id": p.patient_id,
                "age_band": p.age_band,
                "sensitised_to": p.sensitised_to,
                "med_class_on_file": m.medicine_class,
                "asthma_flag": p.asthma_flag,
                "language": p.language,
                "message": " ".join(m.lines),
            })
        eligible = {d["patient_id"] for d in drafts}
        filtered = {"no_alert_species": 0, "med_on_file_none": 0, "not_sensitised": 0}
        for p in patients:
            if p.patient_id in eligible:
                continue
            if species is None:
                filtered["no_alert_species"] += 1
            elif species not in p.sensitised_to:
                filtered["not_sensitised"] += 1
            else:
                filtered["med_on_file_none"] += 1
        scenarios.append({
            "id": sid,
            "label": label,
            "kind": kind,
            "date": date,
            "means": {sp: round(v, 1) for sp, v in means.items()},
            "alerting_species": species,
            "eligible_count": len(drafts),
            "filtered_count": len(patients) - len(drafts),
            "filtered_reasons": filtered,
            "drafts": drafts,
        })
    return {
        "roster_size": len(patients),
        "thresholds": thresholds["alert"],
        "thresholds_status": thresholds["status"],
        "safety_line": reminders.SAFETY_LINE,
        "asthma_line": reminders.ASTHMA_LINE,
        "scenarios": scenarios,
    }


def render_console() -> str:
    blob = json.dumps(console_data(), indent=1, ensure_ascii=True).replace("</", "<\\/")
    return (CONSOLE_BEGIN + "\n"
            + '<script type="application/json" id="nurse-console-data">\n'
            + blob + "\n</script>\n" + CONSOLE_END)


def inject_console(page: str) -> str:
    start = page.index(CONSOLE_BEGIN)
    stop = page.index(CONSOLE_END, start) + len(CONSOLE_END)
    return page[:start] + render_console() + page[stop:]


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="fail if demo/index.html is stale")
    args = parser.parse_args(argv)

    backtest = json.loads(BACKTEST_JSON.read_text())
    page = DEMO_HTML.read_text()
    new_page = inject_console(inject(page, render_tbody(onset_rows(backtest))))
    if args.check:
        if new_page != page:
            print("demo/index.html generated blocks are stale: run eval/render_demo.py", file=sys.stderr)
            return 1
        return 0
    DEMO_HTML.write_text(new_page)
    return 0


if __name__ == "__main__":
    sys.exit(main())
